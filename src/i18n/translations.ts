export type TranslationKey = keyof typeof translations.en;

export function t(lang: Language, key: TranslationKey): string {
  return translations[lang][key] ?? translations.en[key];
}

export function tAuthError(lang: Language, code: AuthErrorCode | string | undefined, fallback?: string): string {
  if (code && code in authErrorMessages[lang]) {
    return authErrorMessages[lang][code as AuthErrorCode];
  }
  return fallback || authErrorMessages[lang].NETWORK_ERROR;
}
